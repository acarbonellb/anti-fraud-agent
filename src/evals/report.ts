/**
 * Renders `evals/report.md`. Deterministic on purpose: CI regenerates it from
 * the recordings and fails if it differs from the committed one, so every
 * behaviour change shows up in the PR diff (#6). No timestamps, no locale.
 */
import { type HistoryEntry, sameSet, setName } from "./history.js";
import type { Metrics } from "./metrics.js";
import {
  byCase,
  computeRunMetrics,
  majorityOutcome,
  type RunMetrics,
  type SpreadMetric,
} from "./runs.js";
import {
  FOOLED_WEBS,
  type FooledResult,
  type FooledRun,
  WEB_LABEL,
} from "./fooled-model.js";
import { type CaseOutcome, type CaseResult, caseOrder } from "./types.js";

export interface ReportSet {
  provider: string;
  model: string;
  promptVersions: string[];
  /** Distinct `YYYY-MM-DD` dates of the recordings' clocks. */
  recordedOn: string[];
  /**
   * The recorded searches against the real web, over every run, and how many
   * failed (#82). Authored pages never fail, so they stay out.
   */
  liveSearches: { attempted: number; failed: number };
  /** One list of case results per run: `runs[0]` is run 1. */
  runs: CaseResult[][];
}

export function renderReport(
  sets: readonly ReportSet[],
  history: readonly HistoryEntry[] = [],
  /** The gated fraud cases run with the fooled model (#82). */
  fooled: readonly FooledResult[] = [],
): string {
  const lines = [
    "# Offline eval report",
    "",
    "Generated by `pnpm eval:replay` from `evals/recordings/`: don't edit it by hand.",
    "The dataset is brief §5 and the metrics brief §4.3. **Gated** leaves out the",
    "cases that need the external tools (#7). **Auto-approved fraud** is a problem",
    "case approved without reaching the admin; CI fails if it is above 0 among the",
    "gated cases. Approved fraud the policy escalated still counts in the",
    "approved-fraud rate, which measures the model. Each set's **History** comes",
    "from `evals/history.jsonl`; why each entry exists, and what was decided, is",
    "in `docs/experiments.md`.",
    "",
    "A set recorded several times per case (#42) shows each metric's mean over",
    "the runs, with the min–max of the four an experiment is decided on, and how",
    "many runs agree on each case (`reject 2/3`). A case is right only when most",
    "of its runs are, so a tie is wrong, and CI fails on a fraud case any run",
    "auto-approved. An entry's **Runs** tells a mean from a single run: two",
    "entries differ only where their ranges don't overlap.",
    "",
  ];
  if (sets.length === 0) {
    lines.push("No recordings yet: run `pnpm eval` with a model.", "");
  }
  const sorted = [...sets].sort((a, b) => compare(setName(a), setName(b)));
  for (const set of sorted) {
    lines.push(
      ...renderSet(
        set,
        history.filter((entry) => sameSet(entry, set)),
      ),
    );
  }
  if (fooled.length > 0) lines.push(...fooledSection(fooled));
  return lines.join("\n");
}

/**
 * Not metrics: the fooled model says what the code guarantees, not how well
 * any model reviews. The code-decided cases are held by the gate; only the
 * ones that rest on the model are listed, so their number stays visible.
 */
function fooledSection(fooled: readonly FooledResult[]): string[] {
  const sorted = [...fooled].sort(
    (a, b) => caseOrder(a.caseId) - caseOrder(b.caseId),
  );
  const byModel = sorted.filter((result) => result.decidedBy === "model");
  const webs = FOOLED_WEBS.map((web) => WEB_LABEL[web].replace(/^with /, ""));
  return [
    "## Fooled-model gate",
    "",
    "Every gated fraud case, run with a model that always proposes a confident",
    "approval with no findings, once with the web as the code's own searches",
    "were recorded and once with the web down. Not part of the metrics. CI fails",
    "if a code-decided case resolves as an approval, or ends `approve` over a",
    "negative finding of the code's own; a model-decided one rests on the",
    "model's judgement, and is listed here with what the fooled model got.",
    "",
    `Code-decided: ${String(sorted.length - byModel.length)} of ${String(sorted.length)} gated fraud cases. Model-decided: ${String(byModel.length)}.`,
    "",
    ...(byModel.length === 0
      ? []
      : [
          `| Case | Title | ${webs.map(capitalized).join(" | ")} |`,
          `| --- | --- | ${webs.map(() => "---").join(" | ")} |`,
          ...byModel.map(
            (result) =>
              `| ${result.caseId} | ${cell(result.title)} | ${FOOLED_WEBS.map(
                (web) =>
                  cell(fooledCell(result.runs.find((run) => run.web === web))),
              ).join(" | ")} |`,
          ),
          "",
        ]),
  ];
}

function fooledCell(run: FooledRun | undefined): string {
  if (run === undefined) return "—";
  if (run.outcome === null) return run.failure ?? "—";
  const { decision, autonomy, reasons } = run.outcome;
  return `${decision} · ${autonomy} (${reasons.join("; ")})`;
}

function capitalized(text: string): string {
  return text.charAt(0).toUpperCase() + text.slice(1);
}

function renderSet(set: ReportSet, history: readonly HistoryEntry[]): string[] {
  const runs = set.runs.map((results) =>
    [...results].sort((a, b) => caseOrder(a.caseId) - caseOrder(b.caseId)),
  );
  const several = runs.length > 1;
  const gated = computeRunMetrics(runs, { includeExternal: false });
  const all = computeRunMetrics(runs, { includeExternal: true });
  const row = (label: string, value: (metrics: RunMetrics) => string) =>
    `| ${label} | ${value(gated)} | ${value(all)} |`;
  const rate = (key: SpreadMetric) => (metrics: RunMetrics) =>
    several
      ? withRange(metrics.mean[key], metrics.spread[key])
      : percent(metrics.mean[key]);
  const mean = (value: (metrics: Metrics) => string) => (m: RunMetrics) =>
    value(m.mean);
  // Outside `Metrics`: the history keeps what decides an experiment, and an
  // entry's schema never changes after it is written (ADR 0014).
  const cost = (external: boolean) =>
    dollars(
      meanCost(runs.flat().filter((result) => external || !result.external)),
    );
  const cases = byCase(runs);

  return [
    `## ${set.provider} / ${set.model}`,
    "",
    `Prompt ${set.promptVersions.map((v) => `\`${v}\``).join(", ") || "—"} · recorded ${set.recordedOn.join(", ") || "—"}` +
      (several
        ? ` · ${String(runs.length)} runs per case: means, with the min–max across runs`
        : ""),
    "",
    liveSearchLine(set.liveSearches),
    "",
    "| Metric | Gated | All cases |",
    "| --- | --- | --- |",
    row(
      "Cases scored",
      mean((m) => `${String(m.scored)} / ${String(m.cases)}`),
    ),
    row("Accuracy", rate("accuracy")),
    row("Approved-fraud rate", rate("approvedFraudRate")),
    row("Auto-approved fraud rate", rate("autoApprovedFraudRate")),
    row(
      "Escalation rate",
      mean((m) => percent(m.escalationRate)),
    ),
    row("Autonomy accuracy", rate("autonomyAccuracy")),
    row(
      "Brier score",
      mean((m) => fixed(m.brier, 3)),
    ),
    row(
      "Mean tokens in / out",
      mean(
        (m) => `${integer(m.meanInputTokens)} / ${integer(m.meanOutputTokens)}`,
      ),
    ),
    row(
      "Mean latency",
      mean((m) =>
        m.meanLatencyMs === null
          ? "—"
          : `${(m.meanLatencyMs / 1000).toFixed(1)} s`,
      ),
    ),
    `| Mean cost per review | ${cost(false)} | ${cost(true)} |`,
    "",
    ...historySection(history),
    ...caseTable(
      "Gated cases",
      cases.filter((results) => results[0]?.external === false),
    ),
    ...caseTable(
      "Cases that need the external tools (#7)",
      cases.filter((results) => results[0]?.external === true),
    ),
  ];
}

/**
 * Whether the metrics were measured with the web: a set whose every live
 * search failed describes an agent that never had web evidence (#82).
 */
function liveSearchLine({
  attempted,
  failed,
}: ReportSet["liveSearches"]): string {
  const counts = `Live web searches: ${String(failed)} failed of ${String(attempted)} attempted`;
  return attempted > 0 && failed === attempted
    ? `${counts}: recorded while web search was down, so these metrics describe the agent without web evidence.`
    : `${counts}.`;
}

/** The set's entries of `evals/history.jsonl`, in the order they were appended. */
function historySection(history: readonly HistoryEntry[]): string[] {
  if (history.length === 0) {
    return [
      "### History",
      "",
      'No entries yet: run `pnpm eval:replay --note "<what changed>"`.',
      "",
    ];
  }
  // Mermaid can't leave a gap: a rate with no cases to measure plots as 0,
  // and the table shows it as «—».
  const line = (value: (entry: HistoryEntry) => number | null) =>
    `  line [${history.map((entry) => String(Number(((value(entry) ?? 0) * 100).toFixed(1)))).join(", ")}]`;
  return [
    "### History",
    "",
    "| Entry | Date | Prompt | Runs | Note | Accuracy | Approved fraud | Auto-approved fraud | Brier |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ...history.map((entry) => {
      // An entry from before repeats, or of one run, has no range.
      const rate = (key: SpreadMetric) =>
        entry.spread === undefined
          ? percent(entry.gated[key])
          : withRange(entry.gated[key], entry.spread.gated[key]);
      return `| ${[
        entry.id,
        entry.date,
        entry.promptVersions.map((v) => `\`${v}\``).join(", ") || "—",
        String(entry.runs ?? 1),
        entry.note,
        rate("accuracy"),
        rate("approvedFraudRate"),
        rate("autoApprovedFraudRate"),
        fixed(entry.gated.brier, 3),
      ]
        .map(cell)
        .join(" | ")} |`;
    }),
    "",
    "Lines, in order: accuracy, approved-fraud rate, auto-approved fraud rate.",
    "",
    "```mermaid",
    "xychart-beta",
    '  title "Gated cases over the history (%)"',
    `  x-axis [${history.map((entry) => entry.id).join(", ")}]`,
    '  y-axis "%" 0 --> 100',
    line((entry) => entry.gated.accuracy),
    line((entry) => entry.gated.approvedFraudRate),
    line((entry) => entry.gated.autoApprovedFraudRate),
    "```",
    "",
  ];
}

function caseTable(
  heading: string,
  cases: readonly (readonly CaseResult[])[],
): string[] {
  if (cases.length === 0) return [];
  return [
    `### ${heading}`,
    "",
    "| Case | Subject | Decision | Autonomy | Confidence | Venue | Policy reasons |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...cases.map((results) =>
      results.length === 1 && results[0] !== undefined
        ? renderCase(results[0])
        : renderRuns(results),
    ),
    "",
  ];
}

function renderCase(result: CaseResult): string {
  const expectedDecision = result.expected.decisions.join(" / ");
  const { outcome } = result;
  const cells =
    outcome === null
      ? [
          `— ${expectedDecision}`,
          `— ${result.expected.autonomy}`,
          "—",
          "—",
          result.failure ?? "—",
        ]
      : [
          result.expected.decisions.includes(outcome.decision)
            ? `✅ ${outcome.decision}`
            : `❌ ${expectedDecision} → ${outcome.decision}`,
          outcome.autonomy === result.expected.autonomy
            ? `✅ ${outcome.autonomy}`
            : `❌ ${result.expected.autonomy} → ${outcome.autonomy}`,
          outcome.confidence.toFixed(2),
          venueCell(outcome.venue),
          reasonsOf(outcome).join("; "),
        ];
  return caseRow(result, outcome, cells);
}

/**
 * One case over several runs: how many runs gave each decision and autonomy,
 * judged by the majority, and the confidence range. Venue and reasons come
 * from a run that gave the majority decision, so they explain it.
 */
function renderRuns(results: readonly CaseResult[]): string {
  const [first] = results;
  if (first === undefined) return "";
  const expectedDecision = first.expected.decisions.join(" / ");
  const outcomes = results.flatMap((result) =>
    result.outcome === null ? [] : [result.outcome],
  );
  const failures = results.flatMap((result, index) =>
    result.failure === null
      ? []
      : [`run ${String(index + 1)}: ${result.failure}`],
  );
  const majority = majorityOutcome(results);
  const shown =
    outcomes.find((outcome) => outcome.decision === majority.decision) ??
    outcomes[0];
  if (shown === undefined) {
    return caseRow(first, null, [
      `— ${expectedDecision}`,
      `— ${first.expected.autonomy}`,
      "—",
      "—",
      failures.join("; "),
    ]);
  }
  const of = results.length;
  const decisions = tally(
    outcomes.map((outcome) => outcome.decision),
    of,
  );
  const autonomies = tally(
    outcomes.map((outcome) => outcome.autonomy),
    of,
  );
  const confidences = outcomes.map((outcome) => outcome.confidence);
  const [low, high] = [Math.min(...confidences), Math.max(...confidences)];
  return caseRow(first, shown, [
    majority.correct
      ? `✅ ${decisions}`
      : `❌ ${expectedDecision} → ${decisions}`,
    majority.autonomyCorrect
      ? `✅ ${autonomies}`
      : `❌ ${first.expected.autonomy} → ${autonomies}`,
    low === high ? low.toFixed(2) : `${low.toFixed(2)}–${high.toFixed(2)}`,
    venueCell(shown.venue),
    [...reasonsOf(shown), ...failures].join("; "),
  ]);
}

function caseRow(
  result: CaseResult,
  outcome: CaseOutcome | null,
  cells: readonly string[],
): string {
  // Invented organizers and artists have no real web (ADR 0015 point 9).
  const title =
    outcome?.authoredWeb === true
      ? `${result.title} (authored web results)`
      : result.title;
  return `| ${[result.caseId, title, ...cells].map(cell).join(" | ")} |`;
}

function reasonsOf(outcome: CaseOutcome): string[] {
  return [
    ...(outcome.endedBy === "submitted" ? [] : [`ended by ${outcome.endedBy}`]),
    ...outcome.reasons,
  ];
}

/** `reject 2/3 · approve 1/3`: the most common first, ties by name. */
function tally(values: readonly string[], of: number): string {
  const counts = new Map<string, number>();
  for (const value of values) counts.set(value, (counts.get(value) ?? 0) + 1);
  return [...counts]
    .sort(([a, x], [b, y]) => y - x || compare(a, b))
    .map(([value, count]) => `${value} ${String(count)}/${String(of)}`)
    .join(" · ");
}

const VENUE_LABELS: Readonly<Record<string, string>> = {
  venue_exists: "venue",
  venue_capacity: "capacity",
  capacity_far_above_venue: "capacity ≥ 2×",
};

/** The venue checks' verdicts (ADR 0015); organizers have none. */
function venueCell(venue: CaseOutcome["venue"]): string {
  if (venue.length === 0) return "—";
  return venue
    .map(({ check, verdict }) => `${VENUE_LABELS[check] ?? check} ${verdict}`)
    .join(" · ");
}

/** Null when a scored case has no price: an unknown cost never averages in as 0. */
function meanCost(results: readonly CaseResult[]): number | null {
  const costs = results.flatMap((result) =>
    result.outcome === null ? [] : [result.outcome.costMicros],
  );
  if (costs.length === 0 || costs.includes(null)) return null;
  return (
    costs.reduce<number>((total, micros) => total + (micros ?? 0), 0) /
    costs.length
  );
}

/** Micro-dollars as dollars, to the hundredth of a cent. */
function dollars(micros: number | null): string {
  return micros === null ? "—" : `$${(micros / 1_000_000).toFixed(4)}`;
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** Pipes would split a table cell; newlines would end the row. */
function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
}

/** `90.0 % (86.7–93.3)`: a mean over runs and its min–max. */
function withRange(
  value: number | null,
  range: [number, number] | null,
): string {
  if (value === null || range === null) return percent(value);
  const [min, max] = range.map((v) => (v * 100).toFixed(1));
  return `${percent(value)} (${min ?? ""}–${max ?? ""})`;
}

export function percent(value: number | null): string {
  return value === null ? "—" : `${(value * 100).toFixed(1)} %`;
}

function fixed(value: number | null, digits: number): string {
  return value === null ? "—" : value.toFixed(digits);
}

function integer(value: number | null): string {
  return value === null ? "—" : String(Math.round(value));
}
