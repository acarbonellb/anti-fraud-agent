/**
 * Renders `evals/report.md`. Deterministic on purpose: CI regenerates it from
 * the recordings and fails if it differs from the committed one, so every
 * behaviour change shows up in the PR diff (#6). No timestamps, no locale.
 */
import { computeMetrics, type Metrics } from "./metrics.js";
import { type CaseResult, caseOrder } from "./types.js";

export interface ReportSet {
  provider: string;
  model: string;
  promptVersions: string[];
  /** Distinct `YYYY-MM-DD` dates of the recordings' clocks. */
  recordedOn: string[];
  results: CaseResult[];
}

export function renderReport(sets: readonly ReportSet[]): string {
  const lines = [
    "# Offline eval report",
    "",
    "Generated by `pnpm eval:replay` from `evals/recordings/`: don't edit it by hand.",
    "The dataset is brief §5 and the metrics brief §4.3. **Gated** leaves out the",
    "cases that need the external tools (#7). **Auto-approved fraud** is a problem",
    "case approved without reaching the admin; CI fails if it is above 0 among the",
    "gated cases. Approved fraud the policy escalated still counts in the",
    "approved-fraud rate, which measures the model.",
    "",
  ];
  if (sets.length === 0) {
    lines.push("No recordings yet: run `pnpm eval` with a model.", "");
  }
  const sorted = [...sets].sort((a, b) =>
    compare(`${a.provider}/${a.model}`, `${b.provider}/${b.model}`),
  );
  for (const set of sorted) lines.push(...renderSet(set));
  return lines.join("\n");
}

function renderSet(set: ReportSet): string[] {
  const results = [...set.results].sort(
    (a, b) => caseOrder(a.caseId) - caseOrder(b.caseId),
  );
  const gated = computeMetrics(results, { includeExternal: false });
  const all = computeMetrics(results, { includeExternal: true });
  const row = (label: string, value: (metrics: Metrics) => string) =>
    `| ${label} | ${value(gated)} | ${value(all)} |`;

  return [
    `## ${set.provider} / ${set.model}`,
    "",
    `Prompt ${set.promptVersions.map((v) => `\`${v}\``).join(", ") || "—"} · recorded ${set.recordedOn.join(", ") || "—"}`,
    "",
    "| Metric | Gated | All cases |",
    "| --- | --- | --- |",
    row("Cases scored", (m) => `${String(m.scored)} / ${String(m.cases)}`),
    row("Accuracy", (m) => percent(m.accuracy)),
    row("Approved-fraud rate", (m) => percent(m.approvedFraudRate)),
    row("Auto-approved fraud rate", (m) => percent(m.autoApprovedFraudRate)),
    row("Escalation rate", (m) => percent(m.escalationRate)),
    row("Autonomy accuracy", (m) => percent(m.autonomyAccuracy)),
    row("Brier score", (m) => fixed(m.brier, 3)),
    row(
      "Mean tokens in / out",
      (m) => `${integer(m.meanInputTokens)} / ${integer(m.meanOutputTokens)}`,
    ),
    row("Mean latency", (m) =>
      m.meanLatencyMs === null
        ? "—"
        : `${(m.meanLatencyMs / 1000).toFixed(1)} s`,
    ),
    "",
    ...caseTable(
      "Gated cases",
      results.filter((result) => !result.external),
    ),
    ...caseTable(
      "Cases that need the external tools (#7)",
      results.filter((result) => result.external),
    ),
  ];
}

function caseTable(heading: string, results: readonly CaseResult[]): string[] {
  if (results.length === 0) return [];
  return [
    `### ${heading}`,
    "",
    "| Case | Subject | Decision | Autonomy | Confidence | Policy reasons |",
    "| --- | --- | --- | --- | --- | --- |",
    ...results.map(renderCase),
    "",
  ];
}

function renderCase(result: CaseResult): string {
  const expectedDecision = result.expected.decisions.join(" / ");
  const { outcome } = result;
  const cells =
    outcome === null
      ? [
          `— ${expectedDecision}`,
          `— ${result.expected.autonomy}`,
          "—",
          result.failure ?? "—",
        ]
      : [
          result.expected.decisions.includes(outcome.decision)
            ? `✅ ${outcome.decision}`
            : `❌ ${expectedDecision} → ${outcome.decision}`,
          outcome.autonomy === result.expected.autonomy
            ? `✅ ${outcome.autonomy}`
            : `❌ ${result.expected.autonomy} → ${outcome.autonomy}`,
          outcome.confidence.toFixed(2),
          [
            ...(outcome.endedBy === "submitted"
              ? []
              : [`ended by ${outcome.endedBy}`]),
            ...outcome.reasons,
          ].join("; "),
        ];
  return `| ${[result.caseId, result.title, ...cells].map(cell).join(" | ")} |`;
}

function compare(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

/** Pipes would split a table cell; newlines would end the row. */
function cell(text: string): string {
  return text.replace(/\|/g, "\\|").replace(/\s*\n\s*/g, " ");
}

export function percent(value: number | null): string {
  return value === null ? "—" : `${(value * 100).toFixed(1)} %`;
}

function fixed(value: number | null, digits: number): string {
  return value === null ? "—" : value.toFixed(digits);
}

function integer(value: number | null): string {
  return value === null ? "—" : String(Math.round(value));
}
